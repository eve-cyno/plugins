#!/usr/bin/env node
// tools/vendor-host.mjs: makes and checks vendor/eve-cyno-host, the generated copy of the desktop host's compiled index modules that
// every check of this repository runs (one source of truth with the app; never edited by hand).
//
//   node tools/vendor-host.mjs --from <desktop git dir> --rev <40-hex commit>
//       Exports the whole tree of that commit with `git archive` into a new folder under the system temp folder (never a worktree,
//       never a write to the desktop checkout), installs the host's locked dependencies from the local npm cache (`npm ci --offline
//       --ignore-scripts`), runs the host's product build, and replaces vendor/eve-cyno-host with the import closure of the modules
//       below, the index scripts, the pinned index keys, the app's LICENSE and NOTICE, and MANIFEST.json.
//   node tools/vendor-host.mjs --check --from <desktop git dir> --rev <40-hex commit> [--root <dir>]
//       First confirms that the commit is on desktop main (an ancestor of, or equal to, refs/remotes/origin/main of the desktop
//       checkout; `git -C <desktop> fetch origin main` first) and stops with exit 1 before anything is exported or built otherwise:
//       the make runs the desktop's own build scripts at that commit, which only desktop main vouches for. Then the same make into
//       the temp folder only; prints every difference from <root>/vendor/eve-cyno-host (default: this repository's) and exits 1 on
//       any. With --root, the vendored tree of another commit is checked (docs/RUNBOOK.md: a tree written by tools/base-tree.mjs).
//       Before the desktop main check, <root>/vendor and <root>/vendor/eve-cyno-host must be real directories (lstat; a link to a
//       correct tree elsewhere fails), as --verify also requires.
//   node tools/vendor-host.mjs --verify [--root <dir>]
//       Needs no desktop: every vendored file against its SHA-256 in MANIFEST.json, no file missing or extra, package.json and
//       package-lock.json hold the host's ajv and semver, the vendored PRODUCT_KEYS.index equal the vendored .pub files, and the
//       vendored build is a product build (no test key).
//
// Exit codes: 0 pass, 1 a difference or a failed check, 2 usage or a step that could not run. Child processes get fixed argument
// lists and never a shell; this tool makes no network request (npm runs offline). git runs with replace refs off and without the
// variables that redirect it (tools/lib/gitsafe.mjs).
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { createRequire, isBuiltin } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { gitArgs, gitEnv } from './lib/gitsafe.mjs';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const VENDOR_DIR = 'vendor/eve-cyno-host';
const MANIFEST = 'MANIFEST.json';

/** The host modules this repository's tools call (plan 3.1). The modules the index scripts load are added from release-lib.mjs. */
export const TOOL_ROOTS = ['market/indexformat.js', 'market/zipread.js', 'market/stagecheck.js', 'market/names.js', 'themes/package.js',
  'minisign.js', 'trustkeys.js', 'updater/manifest.js', 'grants.js'].map(f => `host/dist/${f}`);
/** The desktop's index tools, vendored with the ESM modules they import (release-lib.mjs finds host/dist from its own folder). */
export const SCRIPT_ROOTS = ['scripts/index-build.mjs', 'scripts/index-verify.mjs'];
/** Files taken from the exported tree as they are: the pinned index keys (primary first) and the app's licence and notices. */
export const INDEX_PUBS = ['host/src/keys/index.pub', 'host/src/keys/index-standby.pub'];
export const TREE_FILES = [...INDEX_PUBS, 'LICENSE', 'NOTICE'];
/** The only packages the vendored code may require; package.json pins them at the host's versions. */
export const PACKAGES = ['ajv', 'semver'];
/** Marks host/dist as CommonJS, as the desktop's host/package.json does (this repository's package.json says "type": "module"). */
const HOST_PACKAGE_JSON = 'host/package.json';
const HOST_PACKAGE_BODY = JSON.stringify({ description: 'GENERATED by tools/vendor-host.mjs: host/dist is CommonJS, as in the desktop host.', type: 'commonjs' }, null, 2) + '\n';

const SHA_RE = /^[0-9a-f]{40}$/;
const posix = (p) => p.split(path.sep).join('/');
const sha256 = (b) => crypto.createHash('sha256').update(b).digest('hex');
/** True when `p` (absolute) is `dir` or inside it. */
const inside = (dir, p) => { const r = path.relative(dir, p); return r === '' || (!r.startsWith('..') && !path.isAbsolute(r)); };
/** A safe vendored path: relative, forward slashes, no empty, `.` or `..` segment. */
const safeRel = (p) => typeof p === 'string' && p.length > 0 && p.length <= 400 && !p.includes('\\') && !p.includes('\0')
  && p.split('/').every(s => s !== '' && s !== '.' && s !== '..');

class Refusal extends Error {}
const refuse = (msg) => { throw new Refusal(msg); };

/** Every regular file below `dir` (forward-slash paths relative to it, sorted); a symlink or other non-regular entry goes to `odd`. */
function listFiles(dir, odd = []) {
  const out = [];
  const walk = (d) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const full = path.join(d, e.name);
      const rel = posix(path.relative(dir, full));
      if (e.isDirectory()) walk(full);
      else if (e.isFile()) out.push(rel);
      else odd.push(rel);
    }
  };
  walk(dir);
  return out.sort();
}

/** The package a bare specifier names (`ajv/dist/2020` -> `ajv`, `@a/b/c` -> `@a/b`). */
const packageOf = (spec) => spec.split('/').slice(0, spec.startsWith('@') ? 2 : 1).join('/');

/** Resolves a relative CommonJS require like Node does for the built host: the file, then .js, .json, then <dir>/index.js. */
function resolveRelative(tree, from, spec) {
  const base = path.resolve(tree, path.dirname(from), spec);
  if (!inside(tree, base)) refuse(`${from}: require("${spec}") points outside the exported tree`);
  for (const c of [base, `${base}.js`, `${base}.json`, path.join(base, 'index.js')]) {
    if (fs.existsSync(c) && fs.lstatSync(c).isFile()) return posix(path.relative(tree, c));
  }
  return refuse(`${from}: cannot resolve ${spec}`);
}

/**
 * The CommonJS import closure of `roots` in the built `tree`, read from the literal `require("...")` calls of the built files (never
 * from a list typed by hand). A require whose argument is not one string literal, a package other than PACKAGES, or a file that does
 * not resolve inside the tree is refused, because the closure would then be unknown. Returns sorted {files, packages, builtins}.
 */
export function closureOf(tree, roots) {
  const files = new Set(), packages = new Set(), builtins = new Set();
  const queue = [...roots];
  while (queue.length > 0) {
    const rel = queue.pop();
    if (files.has(rel)) continue;
    const file = path.join(tree, rel);
    if (!fs.existsSync(file) || !fs.lstatSync(file).isFile()) refuse(`closure root or file ${rel} is not in the build`);
    files.add(rel);
    if (!rel.endsWith('.js')) continue;
    const src = fs.readFileSync(file, 'utf8');
    for (const m of src.matchAll(/\brequire\s*\(\s*([^)\s][^)]*)\)/g)) {
      const lit = m[1].match(/^(["'])([^"'\\\n]+)\1\s*$/);
      if (!lit) refuse(`${rel}: non-literal require(${m[1].slice(0, 60)})`);
      const spec = lit[2];
      if (spec.startsWith('./') || spec.startsWith('../')) queue.push(resolveRelative(tree, rel, spec));
      else if (isBuiltin(spec)) builtins.add(spec);
      else if (PACKAGES.includes(packageOf(spec))) packages.add(packageOf(spec));
      else refuse(`${rel}: requires the package ${spec}; the vendored code may require only ${PACKAGES.join(' and ')} and Node built-ins`);
    }
  }
  return { files: [...files].sort(), packages: [...packages].sort(), builtins: [...builtins].sort() };
}

/**
 * The ESM closure of the index scripts: static `import ... from '...'`, side-effect `import '...'` and literal `import('...')`. A
 * relative import is followed; a bare one must be a Node built-in (the scripts load host code only through release-lib.mjs).
 */
export function scriptClosureOf(tree, roots) {
  const files = new Set();
  const queue = [...roots];
  while (queue.length > 0) {
    const rel = queue.pop();
    if (files.has(rel)) continue;
    const file = path.join(tree, rel);
    if (!fs.existsSync(file) || !fs.lstatSync(file).isFile()) refuse(`script ${rel} is not in the tree`);
    files.add(rel);
    const src = fs.readFileSync(file, 'utf8');
    const specs = [
      ...[...src.matchAll(/^\s*(?:import|export)\b[^'"`;]*?\bfrom\s*(['"])([^'"\n]+)\1/gm)].map(m => m[2]),
      ...[...src.matchAll(/^\s*import\s*(['"])([^'"\n]+)\1/gm)].map(m => m[2]),
    ];
    for (const m of src.matchAll(/\bimport\s*\(\s*([^)]*)\)/g)) {
      const lit = m[1].match(/^(["'])([^"'\\\n]+)\1\s*$/);
      if (!lit) refuse(`${rel}: non-literal import(${m[1].slice(0, 60)})`);
      specs.push(lit[2]);
    }
    for (const spec of specs) {
      if (spec.startsWith('./') || spec.startsWith('../')) {
        const target = path.resolve(tree, path.dirname(rel), spec);
        if (!inside(tree, target)) refuse(`${rel}: import '${spec}' points outside the exported tree`);
        queue.push(posix(path.relative(tree, target)));
      } else if (!isBuiltin(spec)) refuse(`${rel}: imports the package ${spec}; the index scripts may import only Node built-ins`);
    }
  }
  return { files: [...files].sort() };
}

/** The host/dist modules release-lib.mjs loads (`require(path.join(dist, 'a', 'b.js'))` in loadHost and loadHostMarket), sorted. */
export function releaseLibRoots(tree) {
  const src = fs.readFileSync(path.join(tree, 'scripts', 'release-lib.mjs'), 'utf8');
  if (!/const dist = path\.join\(ROOT, 'host', 'dist'\)/.test(src)) refuse('scripts/release-lib.mjs has no host/dist loader of the known shape; update tools/vendor-host.mjs');
  const roots = [...src.matchAll(/require\(path\.join\(dist,\s*((?:'[\w.-]+'\s*,?\s*)+)\)\)/g)]
    .map(m => `host/dist/${[...m[1].matchAll(/'([\w.-]+)'/g)].map(x => x[1]).join('/')}`);
  if (roots.length === 0) refuse('scripts/release-lib.mjs has no host/dist loader of the known shape; update tools/vendor-host.mjs');
  return [...new Set(roots)].sort();
}

/** Runs a program with a fixed argument list and no shell; refuses (exit 2) when it fails. */
function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, { stdio: ['ignore', 'inherit', 'inherit'], shell: false, ...opts });
  if (r.error) refuse(`${cmd} ${args[0]}: ${r.error.message}`);
  if (r.status !== 0) refuse(`${cmd} ${args.slice(0, 3).join(' ')} ... exited ${r.status ?? r.signal}`);
  return r;
}
const readOut = (cmd, args, opts = {}) => {
  const r = spawnSync(cmd, args, { encoding: 'utf8', shell: false, stdio: ['ignore', 'pipe', 'pipe'], ...opts });
  return r.status === 0 ? r.stdout.trim() : null;
};
/** `git <args>` in the desktop checkout `from`, replace refs off and no redirecting variable; its trimmed output, or null. */
const gitOut = (from, args) => readOut('git', gitArgs(from, args), { env: gitEnv(process.env) });

/** The desktop's main as the desktop checkout knows it, named in full (a branch or tag named origin/main cannot stand in). */
export const DESKTOP_MAIN = 'refs/remotes/origin/main';

/**
 * Whether desktop commit `rev` is on desktop main in the checkout `from`: an ancestor of DESKTOP_MAIN, or that commit. Returns
 * { on, main } (main: the commit DESKTOP_MAIN names); refuses when the checkout has no DESKTOP_MAIN or git cannot tell.
 */
export function onDesktopMain(from, rev) {
  const main = gitOut(from, ['rev-parse', '--verify', '--quiet', '--end-of-options', `${DESKTOP_MAIN}^{commit}`]);
  if (!main || !SHA_RE.test(main)) refuse(`${from} has no ${DESKTOP_MAIN}: git -C <desktop> fetch origin main, then run the check again`);
  if (gitOut(from, ['cat-file', '-t', `${rev}^{commit}`]) !== 'commit') refuse(`${rev} is not a commit in ${from}`);
  const r = spawnSync('git', gitArgs(from, ['merge-base', '--is-ancestor', rev, main]), { env: gitEnv(process.env), shell: false, stdio: 'ignore' });
  if (r.status === 0) return { on: true, main };
  if (r.status === 1) return { on: false, main };
  return refuse(`git merge-base --is-ancestor ${rev.slice(0, 12)} ${DESKTOP_MAIN} exited ${r.status ?? r.signal}`);
}

/**
 * Makes the vendored tree for desktop `rev` into `<work>/out` and returns {out, manifest, closure}. Steps: whole-tree `git archive`,
 * `npm ci --offline --ignore-scripts` in host/, the host's product build, the closure, the copies, MANIFEST.json.
 */
function make(from, rev, work) {
  if (gitOut(from, ['cat-file', '-t', `${rev}^{commit}`]) !== 'commit') refuse(`${rev} is not a commit in ${from}`);
  const tree = path.join(work, 'tree');
  fs.mkdirSync(tree);
  const tar = path.join(work, 'tree.tar');
  console.log(`vendor-host: git archive ${rev.slice(0, 12)} (whole tree) into a temp folder`);
  run('git', gitArgs(from, ['archive', '--format=tar', `--output=${tar}`, rev]), { env: gitEnv(process.env) });
  run('tar', ['-x', '-f', tar, '-C', tree, '--no-same-owner']);
  fs.rmSync(tar);
  const env = { ...process.env, ELECTRON_SKIP_BINARY_DOWNLOAD: '1', npm_config_update_notifier: 'false', npm_config_fund: 'false', npm_config_audit: 'false' };
  console.log('vendor-host: npm ci --prefix host --ignore-scripts --offline');
  run('npm', ['ci', '--prefix', 'host', '--ignore-scripts', '--offline', '--no-audit', '--no-fund'], { cwd: tree, env });
  console.log('vendor-host: npm --prefix host run build (product)');
  run('npm', ['--prefix', 'host', 'run', 'build'], { cwd: tree, env });

  const buildinfo = fs.readFileSync(path.join(tree, 'host/dist/buildinfo.js'), 'utf8');
  if (!buildinfo.includes('exports.TEST_BUILD = false;')) refuse('host/dist/buildinfo.js is not a product build');
  const dist = closureOf(tree, [...new Set([...TOOL_ROOTS, ...releaseLibRoots(tree)])].sort());
  const scripts = scriptClosureOf(tree, SCRIPT_ROOTS);
  const lock = JSON.parse(fs.readFileSync(path.join(tree, 'host/package-lock.json'), 'utf8'));
  const dependencies = Object.fromEntries(PACKAGES.map(n => {
    const p = lock.packages?.[`node_modules/${n}`];
    if (!p?.version || !p?.integrity) refuse(`host/package-lock.json has no ${n}`);
    return [n, { version: p.version, integrity: p.integrity }];
  }));
  const hostApi = createRequire(path.join(tree, 'host/dist/'))('./manifest.js').HOST_API?.version;
  if (typeof hostApi !== 'string') refuse('host/dist/manifest.js has no HOST_API.version');

  const out = path.join(work, 'out');
  const files = {};
  const put = (rel, bytes, origin) => {
    if (Object.hasOwn(files, rel) || rel === MANIFEST) refuse(`${rel} would be vendored twice`);
    const f = path.join(out, rel);
    fs.mkdirSync(path.dirname(f), { recursive: true });
    fs.writeFileSync(f, bytes);
    files[rel] = { sha256: sha256(bytes), size: bytes.length, origin };
  };
  for (const rel of dist.files) put(rel, fs.readFileSync(path.join(tree, rel)), 'build');
  for (const rel of [...scripts.files, ...TREE_FILES]) put(rel, fs.readFileSync(path.join(tree, rel)), 'tree');
  put(HOST_PACKAGE_JSON, Buffer.from(HOST_PACKAGE_BODY), 'generated');
  const sorted = Object.fromEntries(Object.keys(files).sort().map(k => [k, files[k]]));
  const manifest = {
    schema: 1,
    generator: 'tools/vendor-host.mjs',
    desktop: { commit: rev },
    build: 'npm --prefix host run build (product: no test key)',
    hostApi,
    dependencies,
    roots: [...new Set([...TOOL_ROOTS, ...releaseLibRoots(tree)])].sort(),
    builtins: dist.builtins,
    files: sorted,
  };
  fs.writeFileSync(path.join(out, MANIFEST), JSON.stringify(manifest, null, 2) + '\n');
  const sum = (origin) => Object.values(sorted).filter(f => f.origin === origin);
  const closure = { files: sum('build').length, bytes: sum('build').reduce((a, f) => a + f.size, 0),
    allFiles: Object.keys(sorted).length + 1, allBytes: Object.values(sorted).reduce((a, f) => a + f.size, 0) + fs.statSync(path.join(out, MANIFEST)).size };
  return { out, manifest, closure };
}

/**
 * FAIL lines for `<root>/vendor` and `<root>/vendor/eve-cyno-host` when either is not a real directory (lstat, never followed):
 * through a link there, a correct vendored tree elsewhere would pass every file check while the tree under review holds a link.
 */
export function vendorDirFails(root) {
  for (const rel of ['vendor', VENDOR_DIR]) {
    let st;
    try { st = fs.lstatSync(path.join(root, rel)); } catch (e) { return [`FAIL not-a-directory ${rel}: cannot be read (${e.code ?? e.name})`]; }
    if (!st.isDirectory()) return [`FAIL not-a-directory ${rel}: ${st.isSymbolicLink() ? 'a link' : 'not a directory'}; the vendored tree is real directories only`];
  }
  return [];
}

/** Byte comparison of two trees; returns the differences as `DIFF <kind> <path>` lines. */
function compareTrees(fresh, vendored) {
  const diffs = [];
  const oddA = [], oddB = [];
  const a = listFiles(fresh, oddA);
  const b = fs.existsSync(vendored) ? listFiles(vendored, oddB) : [];
  for (const p of oddB) diffs.push(`DIFF not-regular ${p}`);
  const setB = new Set(b), setA = new Set(a);
  for (const p of a) {
    if (!setB.has(p)) diffs.push(`DIFF missing ${p}`);
    else if (!fs.readFileSync(path.join(fresh, p)).equals(fs.readFileSync(path.join(vendored, p)))) diffs.push(`DIFF changed ${p}`);
  }
  for (const p of b) if (!setA.has(p)) diffs.push(`DIFF extra ${p}`);
  return diffs;
}

/** --verify: returns the FAIL lines (empty when the vendored tree holds). */
export function verifyVendor(root) {
  const notDirs = vendorDirFails(root);
  if (notDirs.length > 0) return notDirs;
  const fails = [];
  const vendor = path.join(root, VENDOR_DIR);
  let m;
  try {
    m = JSON.parse(fs.readFileSync(path.join(vendor, MANIFEST), 'utf8'));
  } catch (e) { return [`FAIL manifest ${VENDOR_DIR}/${MANIFEST} cannot be read (${e.code ?? e.name})`]; }
  const entries = m && typeof m === 'object' && m.files && typeof m.files === 'object' ? Object.entries(m.files) : null;
  if (m?.schema !== 1 || !entries || !SHA_RE.test(m.desktop?.commit ?? '') || !m.dependencies || typeof m.dependencies !== 'object') {
    return [`FAIL manifest ${VENDOR_DIR}/${MANIFEST} is not a schema 1 manifest`];
  }
  for (const [rel, f] of entries) {
    if (!safeRel(rel) || rel === MANIFEST || !/^[0-9a-f]{64}$/.test(f?.sha256 ?? '') || !Number.isSafeInteger(f?.size) || f.size < 0) {
      return [`FAIL manifest ${VENDOR_DIR}/${MANIFEST} has a bad entry ${JSON.stringify(rel).slice(0, 80)}`];
    }
  }
  const odd = [];
  const onDisk = fs.existsSync(vendor) ? listFiles(vendor, odd).filter(p => p !== MANIFEST) : [];
  for (const p of odd) fails.push(`FAIL not-regular ${p}`);
  const named = new Map(entries);
  const present = new Set(onDisk);
  for (const [rel, f] of entries) {
    if (!present.has(rel)) { if (!odd.includes(rel)) fails.push(`FAIL missing ${rel}`); continue; }
    const bytes = fs.readFileSync(path.join(vendor, rel));
    const got = sha256(bytes);
    if (got !== f.sha256 || bytes.length !== f.size) fails.push(`FAIL hash ${rel}: sha256 ${got}, MANIFEST.json ${f.sha256}`);
  }
  for (const p of onDisk) if (!named.has(p)) fails.push(`FAIL extra ${p}`);

  let pkg = {}, lock = {};
  try { pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')); } catch { fails.push('FAIL dependency package.json cannot be read'); }
  try { lock = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'), 'utf8')); } catch { fails.push('FAIL dependency package-lock.json cannot be read'); }
  for (const name of PACKAGES) {
    const want = m.dependencies[name];
    if (!want?.version || !want?.integrity) { fails.push(`FAIL dependency ${name}: MANIFEST.json names no version`); continue; }
    const pinned = pkg.dependencies?.[name];
    if (pinned !== want.version) fails.push(`FAIL dependency ${name}: package.json ${JSON.stringify(pinned)}, the host ${want.version} (an exact pin)`);
    const locked = lock.packages?.[`node_modules/${name}`];
    for (const field of ['version', 'integrity']) {
      if (locked?.[field] !== want[field]) fails.push(`FAIL dependency ${name}: package-lock.json ${field} ${JSON.stringify(locked?.[field])}, the host ${want[field]}`);
    }
  }

  // The trust root, read from the vendored code itself. Only a tree whose every file matched MANIFEST.json is loaded.
  if (fails.length === 0) {
    const req = createRequire(path.join(vendor, 'host', 'dist', 'x.js'));
    const pubLine = (rel) => fs.readFileSync(path.join(vendor, rel), 'utf8').split(/\r?\n/).map(l => l.trim()).filter(l => l && !l.startsWith('untrusted comment:'))[0];
    try {
      const keys = req('./trustkeys.js').PRODUCT_KEYS?.index;
      const pubs = INDEX_PUBS.map(pubLine);
      if (!Array.isArray(keys) || keys.length !== pubs.length || keys.some((k, i) => k !== pubs[i])) {
        fails.push(`FAIL keys host/dist/trustkeys.js PRODUCT_KEYS.index ${JSON.stringify(keys)} differ from ${INDEX_PUBS.join(' and ')} ${JSON.stringify(pubs)}`);
      }
      const b = req('./buildinfo.js');
      if (b.TEST_BUILD !== false || !Array.isArray(b.TEST_INDEX_KEYS) || b.TEST_INDEX_KEYS.length !== 0 || !Array.isArray(b.TEST_RELEASE_KEYS) || b.TEST_RELEASE_KEYS.length !== 0) {
        fails.push('FAIL keys host/dist/buildinfo.js is not a product build (TEST_BUILD or a test key is set)');
      }
    } catch (e) { fails.push(`FAIL keys the vendored trust modules cannot be loaded (${e.code ?? e.name})`); }
  }
  return fails;
}

function usage(msg) {
  console.error(`vendor-host: ${msg}`);
  console.error('usage: node tools/vendor-host.mjs --from <desktop git dir> --rev <40-hex commit>\n'
    + '       node tools/vendor-host.mjs --check --from <desktop git dir> --rev <40-hex commit> [--root <dir>]\n'
    + '       node tools/vendor-host.mjs --verify [--root <dir>]');
  process.exit(2);
}

function parseArgs(argv) {
  const o = { mode: 'make', from: null, rev: null, root: REPO };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    const val = () => { const v = argv[++i]; if (v === undefined || v.startsWith('--')) usage(`${a} needs a value`); return v; };
    if (a === '--verify') o.mode = o.mode === 'make' ? 'verify' : usage('one of --verify and --check');
    else if (a === '--check') o.mode = o.mode === 'make' ? 'check' : usage('one of --verify and --check');
    else if (a === '--from') o.from = val();
    else if (a === '--rev') o.rev = val();
    else if (a === '--root') o.root = path.resolve(val());
    else usage(`unknown argument ${JSON.stringify(a).slice(0, 60)}`);
  }
  if (o.mode === 'verify') { if (o.from || o.rev) usage('--verify takes no --from or --rev'); return o; }
  if (!o.from || !o.rev) usage('--from and --rev are both needed');
  if (!SHA_RE.test(o.rev)) usage('--rev must be a full 40-hex commit id (a pin, never a branch name)');
  if (!fs.existsSync(o.from) || !fs.statSync(o.from).isDirectory()) usage('--from must be the desktop git checkout');
  o.from = fs.realpathSync(o.from);
  return o;
}

function main() {
  const o = parseArgs(process.argv.slice(2));
  if (o.mode === 'verify') {
    const fails = verifyVendor(o.root);
    if (fails.length > 0) { for (const f of fails) console.error(f); process.exit(1); }
    const m = JSON.parse(fs.readFileSync(path.join(o.root, VENDOR_DIR, MANIFEST), 'utf8'));
    console.log(`PASS ${VENDOR_DIR}: ${Object.keys(m.files).length} files match MANIFEST.json (desktop ${m.desktop.commit.slice(0, 12)}, host API ${m.hostApi})`);
    return;
  }
  const work = fs.mkdtempSync(path.join(fs.realpathSync(os.tmpdir()), 'eve-cyno-vendor-'));
  try {
    if (inside(o.from, work) || inside(fs.realpathSync(o.root), work)) refuse('the temp folder is inside a repository; set TMPDIR to a folder outside every repository');
    if (o.mode === 'check') {
      // Before the make: the tree under review must hold vendor/eve-cyno-host as real directories, not a link to a correct tree.
      const notDirs = vendorDirFails(o.root);
      if (notDirs.length > 0) {
        for (const f of notDirs) console.error(`${f}; nothing was exported or built`);
        process.exitCode = 1;
        return;
      }
      // Before the make, which runs the desktop's npm ci and build scripts at o.rev: only a commit of desktop main is built.
      const d = onDesktopMain(o.from, o.rev);
      if (!d.on) {
        console.error(`FAIL desktop ${o.rev} is not on desktop main (${DESKTOP_MAIN} ${d.main}): nothing was exported or built; `
          + 'the check builds only a desktop commit of main');
        process.exitCode = 1;
        return;
      }
      console.log(`vendor-host: desktop ${o.rev.slice(0, 12)} is on desktop main (${DESKTOP_MAIN} ${d.main.slice(0, 12)})`);
    }
    const { out, closure } = make(o.from, o.rev, work);
    console.log(`vendor-host: closure host/dist ${closure.files} files, ${closure.bytes} bytes; vendored tree ${closure.allFiles} files, ${closure.allBytes} bytes`);
    const target = path.join(o.root, VENDOR_DIR);
    if (o.mode === 'check') {
      const diffs = compareTrees(out, target);
      if (diffs.length > 0) {
        for (const d of diffs) console.error(d);
        console.error(`FAIL ${VENDOR_DIR} differs from a fresh make from desktop ${o.rev.slice(0, 12)}: node tools/vendor-host.mjs --from <desktop> --rev ${o.rev}`);
        process.exitCode = 1;
      } else console.log(`PASS ${VENDOR_DIR} equals a fresh make from desktop ${o.rev.slice(0, 12)} (${closure.allFiles} files)`);
      return;
    }
    // Replace the vendored tree: the new one is copied beside it first, so a failed copy leaves the old tree in place.
    const next = path.join(o.root, 'vendor', `.eve-cyno-host.new-${process.pid}`);
    const old = path.join(o.root, 'vendor', `.eve-cyno-host.old-${process.pid}`);
    fs.cpSync(out, next, { recursive: true });
    if (fs.existsSync(target)) fs.renameSync(target, old);
    fs.renameSync(next, target);
    fs.rmSync(old, { recursive: true, force: true });
    console.log(`vendor-host: wrote ${VENDOR_DIR} from desktop ${o.rev}`);
  } catch (e) {
    if (!(e instanceof Refusal)) throw e;
    console.error(`vendor-host: ${e.message}`);
    process.exitCode = 2;
  } finally {
    fs.rmSync(work, { recursive: true, force: true });
  }
}

